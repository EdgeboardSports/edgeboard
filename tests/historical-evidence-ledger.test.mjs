import assert from 'node:assert/strict';
import {createHistoricalEvidenceLedger} from '../scripts/historical-evidence-ledger.mjs';
import {renderResearchView} from '../scripts/historical-research-view.mjs';
const ledger=createHistoricalEvidenceLedger();
const base={eventId:'fictional-event',market:'player_shots_on_goal',subjectId:'fictional-player',line:2.5,side:'Over'};
const prediction={...base,id:'prediction-1',probability:.62,predictedAt:'2026-01-01T17:00:00Z',startTime:'2026-01-01T19:00:00Z'};
const quote={...base,bookmaker:'fictional-book',decimal:2.1,observedAt:'2026-01-01T16:55:00Z',source:'synthetic-fixture'};
const settlement={...base,predictionId:'prediction-1',gradedAt:'2026-01-02T01:00:00Z',result:'win'};
ledger.append({type:'prediction',data:prediction});
ledger.append({type:'quote',data:quote});
const before=ledger.evaluate();
assert.equal(before.counts.matched,1);
assert.equal(before.summary.paperROI,null);
assert.equal(before.summary.unresolved,1);
const digest=ledger.append({type:'settlement',data:settlement});
assert.equal(ledger.verify().head,digest);
const after=ledger.evaluate();
assert.equal(after.summary.paperROI,1.1);
assert.equal(after.summary.settled,1);
assert.equal(ledger.evaluate({asOf:'2026-01-01T20:00:00Z'}).summary.paperROI,null);
assert.throws(()=>ledger.append({type:'prediction',data:prediction}),/Duplicate/);
assert.throws(()=>ledger.append({type:'quote',data:{...quote,source:'unknown'}}),/source/);
assert.throws(()=>ledger.append({type:'settlement',data:{...settlement,subjectId:'wrong'}}),/mismatch/);
assert.throws(()=>ledger.append({type:'settlement',data:{...settlement,result:'loss'}}),/later/);
const read=ledger.read();read[0].data.probability=.1;
assert.throws(()=>ledger.verify(read),/integrity/);
assert.equal(ledger.verify().verified,true);
const html=renderResearchView(after);
assert(html.includes('SYNTHETIC DATA'));
assert(html.includes('Paper ROI'));
assert(!html.includes('<script'));
assert.throws(()=>renderResearchView({}));
console.log('Historical evidence: append-only hash chain, source gating, corrections, as-of cutoff, settlement and offline HTML view passed');
