import assert from 'node:assert/strict';
import {appendResearchEvent,verifyResearchChain,reportResearchLedger} from '../scripts/historical-odds-ledger.mjs';
const predictedAt='2026-01-01T18:00:00Z',startTime='2026-01-01T19:00:00Z';
const prediction={id:'fixture-1',eventId:'fictional-game',market:'player_shots_on_goal',subjectId:'fictional-player',line:2.5,side:'Over',probability:.6,predictedAt,startTime};
const quote={eventId:prediction.eventId,market:prediction.market,subjectId:prediction.subjectId,line:2.5,side:'Over',bookmaker:'fictional-book',decimal:2.1,observedAt:'2026-01-01T17:55:00Z',source:'synthetic-fixture'};
let ledger=[];
ledger=appendResearchEvent(ledger,{type:'quote',data:quote},{recordedAt:'2026-01-01T17:56:00Z'});
ledger=appendResearchEvent(ledger,{type:'prediction',data:prediction},{recordedAt:'2026-01-01T18:00:01Z'});
ledger=appendResearchEvent(ledger,{type:'settlement',data:{predictionId:prediction.id,result:'win'}},{recordedAt:'2026-01-02T01:00:00Z'});
assert.equal(verifyResearchChain(ledger).count,3);
const original=JSON.stringify(ledger);
const early=reportResearchLedger(ledger,{asOf:'2026-01-01T18:30:00Z'});
assert.equal(early.summary.unresolved,1);
assert.equal(early.summary.paperROI,null);
const after=reportResearchLedger(ledger,{asOf:'2026-01-02T02:00:00Z'});
assert.equal(after.summary.paperProfitUnits,1.1);
assert.equal(after.summary.paperROI,1.1);
assert.equal(after.ledger.visibleEntries,3);
assert.equal(JSON.stringify(ledger),original);
const changed=structuredClone(ledger);changed[0].data.decimal=1.4;
assert.throws(()=>verifyResearchChain(changed),/digest/);
assert.throws(()=>appendResearchEvent(ledger,{type:'quote',data:quote},{recordedAt:'2026-01-01T17:54:00Z'}),/exist by recorded/);
assert.throws(()=>appendResearchEvent(ledger,{type:'prediction',data:prediction},{recordedAt:'2026-01-01T17:59:00Z'}),/exist by recorded/);
const corrected=appendResearchEvent(ledger,{type:'settlement',data:{predictionId:prediction.id,result:'loss'}},{recordedAt:'2026-01-03T01:00:00Z'});
assert.equal(reportResearchLedger(corrected,{asOf:'2026-01-02T02:00:00Z'}).summary.paperProfitUnits,1.1);
assert.equal(reportResearchLedger(corrected,{asOf:'2026-01-03T02:00:00Z'}).summary.paperProfitUnits,-1);
