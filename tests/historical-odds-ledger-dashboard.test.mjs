import assert from 'node:assert/strict';
import {appendResearchEvent,verifyResearchChain,reportResearchLedger} from '../scripts/historical-odds-ledger.mjs';
import {fixtureLedger,renderOddsResearchDashboard} from '../scripts/historical-odds-dashboard.mjs';
const events=fixtureLedger();
assert.equal(verifyResearchChain(events).count,3);
const report=reportResearchLedger(events,{mode:'synthetic',asOf:'2026-01-02T00:00:00Z'});
assert.equal(report.counts.matched,1);
assert.equal(report.summary.paperProfitUnits,1.1);
assert.equal(report.summary.paperROI,1.1);
assert.equal(report.ledger.settlements,1);
const before=reportResearchLedger(events,{mode:'synthetic',asOf:'2026-01-01T18:30:00Z'});
assert.equal(before.summary.unresolved,1);
assert.equal(before.summary.paperROI,null);
assert.throws(()=>verifyResearchChain(events.map((x,i)=>i===1?{...x,data:{...x.data,decimal:99}}:x)),/digest/);
assert.throws(()=>appendResearchEvent(events,{type:'quote',data:{...events[0].data,observedAt:'2026-01-01T19:00:00Z'}},{recordedAt:'2026-01-01T17:59:00Z'}));
const html=renderOddsResearchDashboard(report);
assert(html.includes('FABRICATED SYNTHETIC DATA'));
assert(html.includes('By market'));
assert(html.includes('By sportsbook'));
assert(html.includes('By estimated EV tier'));
assert(!html.includes('Bearer '));
assert.throws(()=>renderOddsResearchDashboard({...report,mode:'licensed-historical',dataIsSynthetic:false}));
let late=[];
const prediction={...events[1].data,id:'late'};
late=appendResearchEvent(late,{type:'prediction',data:prediction},{recordedAt:'2026-01-01T18:00:00Z'});
late=appendResearchEvent(late,{type:'quote',data:events[0].data},{recordedAt:'2026-01-01T18:01:00Z'});
const lateReport=reportResearchLedger(late,{mode:'synthetic',asOf:'2026-01-02T00:00:00Z'});
assert.equal(lateReport.counts.matched,0);
assert.throws(()=>appendResearchEvent(events,{type:'settlement',data:{predictionId:'fake-pick-1',result:'win'}},{recordedAt:'2026-01-01T18:59:00Z'}),/timestamp/);
let pregame=[];
pregame=appendResearchEvent(pregame,{type:'prediction',data:events[1].data},{recordedAt:'2026-01-01T18:00:00Z'});
pregame=appendResearchEvent(pregame,{type:'settlement',data:{predictionId:'fake-pick-1',result:'win'}},{recordedAt:'2026-01-01T18:30:00Z'});
const earlyGrade=reportResearchLedger(pregame,{mode:'synthetic',asOf:'2026-01-02T00:00:00Z'});
assert.equal(earlyGrade.ledger.rejected.unknownSettlements,1);
assert.equal(earlyGrade.summary.unresolved,0); // no quote matched
const altered=events.map((e,i)=>i===1?{...e,recordedAt:'2026-01-01T17:00:00Z'}:e);
assert.throws(()=>verifyResearchChain(altered),/structure|digest/);
console.log('Research odds ledger and dashboard: chain integrity, pre-prediction quote receipt, as-of settlement, tamper rejection, synthetic-only UI passed.');
